interface I18nContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("c2u_lang") as Language;
    return saved && ["pt", "en", "es"].includes(saved) ? saved : "pt"; // pt ou en
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("c2u_lang", lang);
  };

  const t = (key: string, params?: Record<string, string | number>): string => {
    let str = dictionaries[language]?.[key] || dictionaries.en?.[key] || dictionaries.pt?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      });
    }
    return str;
  };

  const value = useMemo(() => ({ language, setLanguage, t }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useTranslation must be used within LanguageProvider");
  return ctx;
}